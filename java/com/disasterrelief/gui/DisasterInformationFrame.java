    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    

    String name = jTextField1.getText().trim();
    String location = jTextField2.getText().trim();
    String date = jTextField3.getText().trim();
    String description = jTextArea1.getText().trim();
    String affectedText = jTextField4.getText().trim();
    String severity = jComboBox1.getSelectedItem().toString();
    String urgency = jComboBox2.getSelectedItem().toString();

    if (name.isEmpty() || location.isEmpty() || date.isEmpty()
            || description.isEmpty() || affectedText.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Please fill in all fields!",
                "Missing Information",
                javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    try {
        java.sql.Date disasterDate = java.sql.Date.valueOf(date);
        int affectedPeople = Integer.parseInt(affectedText);

        if (affectedPeople < 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Affected people cannot be negative.");
            return;
        }

        String sql = "INSERT INTO disasters "
                + "(disaster_name, location, disaster_date, severity, "
                + "disaster_description, urgency, affected_people) "
                + "VALUES (?, ?, ?, ?, ?, ?, ?)";

        try (java.sql.Connection con = DBConnection.getConnection();
             java.sql.PreparedStatement ps = con.prepareStatement(sql)) {

            ps.setString(1, name);
            ps.setString(2, location);
            ps.setDate(3, disasterDate);
            ps.setString(4, severity);
            ps.setString(5, description);
            ps.setString(6, urgency);
            ps.setInt(7, affectedPeople);

            ps.executeUpdate();

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Disaster information saved successfully!",
                    "Success",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE);
        }

    } catch (IllegalArgumentException e) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Enter the date as yyyy-mm-dd and affected people as a whole number.");
    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Could not save disaster: " + e.getMessage());
    }


    }//GEN-LAST:event_jButton1ActionPerformed

