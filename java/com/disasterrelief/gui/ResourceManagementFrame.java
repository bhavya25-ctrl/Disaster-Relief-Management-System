    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
       
String id = jTextField1.getText().trim();
String name = jTextField2.getText().trim();
String category = jComboBox1.getSelectedItem().toString();
String quantityText = jTextField3.getText().trim();
String location = jTextField4.getText().trim();
String status = jComboBox2.getSelectedItem().toString();

if (id.isEmpty() || name.isEmpty() || quantityText.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Please fill in Resource ID, Resource Name, and Quantity.");
    return;
}

try {
    int quantity = Integer.parseInt(quantityText);

    if (quantity < 0) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Quantity cannot be negative.");
        return;
    }

    String sql = "INSERT INTO resources "
            + "(resource_id, resource_name, category, quantity, location, status) "
            + "VALUES (?, ?, ?, ?, ?, ?)";

    try (java.sql.Connection con = DBConnection.getConnection();
         java.sql.PreparedStatement ps = con.prepareStatement(sql)) {

        ps.setString(1, id);
        ps.setString(2, name);
        ps.setString(3, category);
        ps.setInt(4, quantity);
        ps.setString(5, location);
        ps.setString(6, status);

        ps.executeUpdate();

        javax.swing.JOptionPane.showMessageDialog(this,
                "Resource added successfully!");

        jTextField1.setText("");
        jTextField2.setText("");
        jTextField3.setText("");
        jTextField4.setText("");
    }

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Quantity must be a valid whole number.");
} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Could not add resource: " + e.getMessage());
}

    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
       
String id = jTextField1.getText().trim();
String name = jTextField2.getText().trim();
String category = jComboBox1.getSelectedItem().toString();
String quantityText = jTextField3.getText().trim();
String location = jTextField4.getText().trim();
String status = jComboBox2.getSelectedItem().toString();

if (id.isEmpty() || name.isEmpty() || quantityText.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Please fill in Resource ID, Resource Name, and Quantity.");
    return;
}

try {
    int quantity = Integer.parseInt(quantityText);

    if (quantity < 0) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Quantity cannot be negative.");
        return;
    }

    String sql = "UPDATE resources SET resource_name = ?, "
            + "category = ?, quantity = ?, location = ?, status = ? "
            + "WHERE resource_id = ?";

    try (java.sql.Connection con = DBConnection.getConnection();
         java.sql.PreparedStatement ps = con.prepareStatement(sql)) {

        ps.setString(1, name);
        ps.setString(2, category);
        ps.setInt(3, quantity);
        ps.setString(4, location);
        ps.setString(5, status);
        ps.setString(6, id);

        int rowsUpdated = ps.executeUpdate();

        if (rowsUpdated > 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Resource updated successfully!");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Resource ID not found. Please enter an existing ID.");
        }
    }

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Quantity must be a valid whole number.");
} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Could not update resource: " + e.getMessage());
}

    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
     
String id = jTextField1.getText().trim();

if (id.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Please enter the Resource ID to delete.");
    return;
}

int confirm = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete resource " + id + "?",
        "Confirm Delete",
        javax.swing.JOptionPane.YES_NO_OPTION
);

if (confirm != javax.swing.JOptionPane.YES_OPTION) {
    return;
}

String sql = "DELETE FROM resources WHERE resource_id = ?";

try (java.sql.Connection con = DBConnection.getConnection();
     java.sql.PreparedStatement ps = con.prepareStatement(sql)) {

    ps.setString(1, id);

    int rowsDeleted = ps.executeUpdate();

    if (rowsDeleted > 0) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Resource deleted successfully!");

        jTextField1.setText("");
        jTextField2.setText("");
        jTextField3.setText("");
        jTextField4.setText("");
    } else {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Resource ID not found.");
    }

} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Could not delete resource: " + e.getMessage());
}

    }//GEN-LAST:event_jButton3ActionPerformed

