    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
 
String name = jTextField1.getText().trim();
String username = jTextField2.getText().trim();
String password = jPasswordField1.getText();
String confirmPassword = jPasswordField2.getText();

if (name.isEmpty() || username.isEmpty()
        || password.isEmpty() || confirmPassword.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this, "Please fill in all fields.");

} else if (!username.matches(".*[^a-zA-Z0-9].*")) {

    javax.swing.JOptionPane.showMessageDialog(
            this, "Username must contain a special character.");

} else if (password.length() < 6) {

    javax.swing.JOptionPane.showMessageDialog(
            this, "Password must be at least 6 characters.");

} else if (!password.equals(confirmPassword)) {

    javax.swing.JOptionPane.showMessageDialog(
            this, "Passwords do not match.");

} else {
    String sql = "INSERT INTO users (full_name, username, password) VALUES (?, ?, ?)";

    try (java.sql.Connection con = DBConnection.getConnection();
         java.sql.PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setString(1, name);
        pst.setString(2, username);
        pst.setString(3, password);

        pst.executeUpdate();

        javax.swing.JOptionPane.showMessageDialog(
                this, "Account created successfully!");

        new LoginFrame().setVisible(true);
        this.dispose();

    } catch (java.sql.SQLIntegrityConstraintViolationException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "This username is already registered.");

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Registration failed: " + e.getMessage());
    }
}

    }//GEN-LAST:event_jButton1ActionPerformed

