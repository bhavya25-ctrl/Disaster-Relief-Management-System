private void loadReportData() {
    String totalResourcesSql =
            "SELECT COUNT(*) FROM resources";

    String totalRequestsSql =
            "SELECT COUNT(*) FROM relief_requests";

    String activeDisastersSql =
            "SELECT COUNT(*) FROM disasters";

    String distributedResourcesSql =
            "SELECT COALESCE(SUM(quantity), 0) "
            + "FROM resources WHERE status = 'Distributed'";

    try (java.sql.Connection con = DBConnection.getConnection()) {

        try (java.sql.Statement st = con.createStatement()) {

            try (java.sql.ResultSet rs =
                    st.executeQuery(totalResourcesSql)) {
                if (rs.next()) {
                    jTextField1.setText(
                            String.valueOf(rs.getInt(1)));
                }
            }

            try (java.sql.ResultSet rs =
                    st.executeQuery(totalRequestsSql)) {
                if (rs.next()) {
                    jTextField2.setText(
                            String.valueOf(rs.getInt(1)));
                }
            }

            try (java.sql.ResultSet rs =
                    st.executeQuery(activeDisastersSql)) {
                if (rs.next()) {
                    jTextField3.setText(
                            String.valueOf(rs.getInt(1)));
                }
            }

            try (java.sql.ResultSet rs =
                    st.executeQuery(distributedResourcesSql)) {
                if (rs.next()) {
                    jTextField4.setText(
                            String.valueOf(rs.getInt(1)));
                }
            }
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Could not load reports: " + e.getMessage(),
                "Database Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
}


