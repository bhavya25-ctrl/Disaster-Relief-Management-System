    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
     
                                        
    String fullName = jTextField1.getText().trim();
    String location = jTextField2.getText().trim();
    String peopleText = jTextField3.getText().trim();

    String reliefType = jComboBox1.getSelectedItem().toString();
    String severity = jComboBox2.getSelectedItem().toString();
    String urgency = jComboBox3.getSelectedItem().toString();

    if (fullName.isEmpty() || location.isEmpty() || peopleText.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Please fill in all fields!");
        return;
    }

    try {
        int peopleAffected = Integer.parseInt(peopleText);

        if (peopleAffected < 0) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Number of people affected cannot be negative.");
            return;
        }

        String sql = "INSERT INTO relief_requests "
                + "(full_name, location, relief_type, people_affected, severity, urgency) "
                + "VALUES (?, ?, ?, ?, ?, ?)";

        try (java.sql.Connection con = DBConnection.getConnection();
             java.sql.PreparedStatement ps = con.prepareStatement(sql)) {

            ps.setString(1, fullName);
            ps.setString(2, location);
            ps.setString(3, reliefType);
            ps.setInt(4, peopleAffected);
            ps.setString(5, severity);
            ps.setString(6, urgency);

            ps.executeUpdate();

            javax.swing.JOptionPane.showMessageDialog(
                    this, "Relief request submitted successfully!");
        }

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Please enter a valid whole number for people affected.");
    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Could not submit request: " + e.getMessage());
    }


    }//GEN-LAST:event_jButton2ActionPerformed

